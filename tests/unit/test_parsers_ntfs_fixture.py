"""A small NTFS image with known live, deleted, recycle-bin, and shortcut files.

Built with ``mkfs.ntfs`` and ``ntfs-3g`` (needs root and FUSE), used by the NTFS module tests.
Every file is generated text or generated bytes: no real user data, no media of people.
``build_ntfs_image(path)`` returns the ground truth the tests check against.

The tests here only check the builder itself (the image holds what the ground truth says,
read back with The Sleuth Kit).
"""

