SID = "S-1-5-21-111-222-333-1001"
RUN_ID = "R-20261115T000000Z-abcdef"
EVIDENCE_SHA = "ab" * 32
EPOCH = dt.datetime(1601, 1, 1, tzinfo=dt.UTC)


def ticks(when: dt.datetime, frac: int = 0) -> int:
    return int((when - EPOCH).total_seconds()) * filetime.TICKS_PER_SECOND + frac


def png_bytes(w: int = 48, h: int = 32, color: tuple[int, int, int] = (40, 120, 200)) -> bytes:
    """A plain coloured rectangle as PNG (generated shapes only)."""
    raw = b"".join(b"\x00" + bytes(color) * w for _ in range(h))

    def chunk(kind: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(kind + data) & 0xFFFFFFFF
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", crc)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(raw))
        + chunk(b"IEND", b"")
    )


def ntfs_tools_ok() -> str:
    """Empty string when the fixture can be built here, else the reason it cannot."""
    if os.geteuid() != 0:
        return "needs root (ntfs-3g mount)"
    for tool in ("mkfs.ntfs", "ntfs-3g", "fls", "icat", "fsstat"):
        if not shutil.which(tool):
            return f"needs {tool}"
    if not Path("/dev/fuse").exists():
        return "needs /dev/fuse"
    return ""


def _run(*argv: str) -> None:
    subprocess.run(list(argv), check=True, capture_output=True)


def usn_blob(entries: list[tuple[int, int, int, int, str, int, int]]) -> bytes:
    """USN_RECORD_V2 records: (entry, seq, parent, parent_seq, name, reason, usn)."""
    base = ticks(dt.datetime(2026, 11, 2, 9, 0, 0, tzinfo=dt.UTC), 1_234_567)
    out = b""
    for n, (entry, seq, parent, pseq, name, reason, number) in enumerate(entries):
        out += usn.build_v2(
            entry=entry,
            seq=seq,
            parent_entry=parent,
            parent_seq=pseq,
            usn=number,
            timestamp=base + n * filetime.TICKS_PER_SECOND,
            reason=reason,
            name=name,
        )
    return out


def build_ntfs_image(img: Path, *, size_mib: int = 48) -> dict[str, Any]:
    """Build the image at ``img`` and return its ground truth."""
    img.unlink(missing_ok=True)
    with open(img, "wb") as fh:
        fh.truncate(size_mib * 1024 * 1024)
    _run("mkfs.ntfs", "-Q", "-F", "-L", "AIRLOCKT", str(img))
    mnt = img.parent / f"{img.name}.mnt"
    mnt.mkdir(exist_ok=True)
    _run("ntfs-3g", "-o", "streams_interface=windows", str(img), str(mnt))
    truth: dict[str, Any] = {"sid": SID}
    try:
        docs = mnt / "Docs"
        docs.mkdir()
        (docs / "keep.txt").write_text("hello\n")
        (docs / "gone.txt").write_text("plan for tuesday\n")
        notes = "".join(f"line {i:04d} of generated notes\n" for i in range(400))
        (docs / "old-notes.txt").write_text(notes)
        (docs / "keep.txt:extra").write_text("stream data\n")
        desktop = mnt / "Users" / "Test" / "Desktop"
        desktop.mkdir(parents=True)
        lnk_times = {
            "created": ticks(dt.datetime(2026, 10, 1, 8, 0, 0, tzinfo=dt.UTC), 1_000_000),
            "accessed": ticks(dt.datetime(2026, 10, 3, 9, 30, 0, tzinfo=dt.UTC), 5),
            "modified": ticks(dt.datetime(2026, 10, 2, 12, 15, 30, tzinfo=dt.UTC), 0),
        }
        (desktop / "report.lnk").write_bytes(
            lnk.build(
                "C:\\Users\\Test\\Documents\\report.txt",
                size=4321,
                serial=0x1234ABCD,
                label="DATA",
                **lnk_times,
            )
        )
        jl = mnt / "Users" / "Test" / "Recent"
        jl.mkdir(parents=True)
        (jl / "5f7b5f1e01b83767.automaticDestinations-ms").write_bytes(b"generated" * 64)
        rb = mnt / "$Recycle.Bin" / SID
        rb.mkdir(parents=True)
        del_v2 = ticks(dt.datetime(2026, 11, 1, 10, 20, 30, tzinfo=dt.UTC), 1_234_567)
        del_v1 = ticks(dt.datetime(2025, 2, 3, 4, 5, 6, tzinfo=dt.UTC))
        del_gone = ticks(dt.datetime(2026, 11, 5, 7, 0, 0, tzinfo=dt.UTC), 42)
        (rb / "$IAB12CD.txt").write_bytes(
            recycle.build("C:\\Users\\Test\\Documents\\draft.txt", 42, del_v2, version=2)
        )
        (rb / "$RAB12CD.txt").write_bytes(b"d" * 42)
        (rb / "$IEF34GH.pdf").write_bytes(
            recycle.build("C:\\Users\\Test\\Downloads\\manual.pdf", 2048, del_v1, version=1)
        )
        (rb / "$IZZ99YY.txt").write_bytes(
            recycle.build("C:\\Temp\\scratch.txt", 7, del_gone, version=2)
        )
        (rb / "$RZZ99YY.txt").write_bytes(b"s" * 7)
        # Carving targets: a picture and USN records in a file that is then deleted, so their
        # clusters are unallocated.
        pic = png_bytes()
        (docs / "picture.png").write_bytes(pic + b"\0" * (8192 - len(pic) % 8192))
        blob = usn_blob([(4242, 3, 5, 5, "carved-name.txt", usn.FILE_DELETE | 0x80000000, 9000)])
        (docs / "usn-like.bin").write_bytes(blob.ljust(16384, b"\0"))
        os.sync()
        for victim in ("gone.txt", "old-notes.txt", "picture.png", "usn-like.bin"):
            (docs / victim).unlink()
        (rb / "$IZZ99YY.txt").unlink()
        (rb / "$RZZ99YY.txt").unlink()
        os.sync()
    finally:
        _run("umount", str(mnt))
        mnt.rmdir()
    truth.update(
        {
            "live": ["/Docs/keep.txt", "/Users/Test/Desktop/report.lnk"],
            "deleted": ["/Docs/gone.txt", "/Docs/old-notes.txt"],
            "ads": "/Docs/keep.txt:extra",
            "recycle": {
                "$IAB12CD.txt": {
                    "path": "C:\\Users\\Test\\Documents\\draft.txt",
                    "size": 42,
                    "deleted": filetime.to_iso(del_v2),
                    "version": 2,
                    "r": "present",
                    "allocated": True,
                },
                "$IEF34GH.pdf": {
                    "path": "C:\\Users\\Test\\Downloads\\manual.pdf",
                    "size": 2048,
                    "deleted": filetime.to_iso(del_v1),
                    "version": 1,
                    "r": "missing",
                    "allocated": True,
                },
                "$IZZ99YY.txt": {
                    "path": "C:\\Temp\\scratch.txt",
                    "size": 7,
                    "deleted": filetime.to_iso(del_gone),
                    "version": 2,
                    "r": "deleted",
                    "allocated": False,
                },
            },
            "lnk": {
                "path": "/Users/Test/Desktop/report.lnk",
                "target": "C:\\Users\\Test\\Documents\\report.txt",
                "times": {k: filetime.to_iso(v) for k, v in lnk_times.items()},
                "serial": "1234ABCD",
            },
            "png_sha256": hashlib.sha256(pic).hexdigest(),
            "carved_usn_name": "carved-name.txt",
        }
    )
    return truth


def tool_runner(workdir: Path) -> Any:
    """``ctx.tool`` for tests: runs the real tool unsandboxed through ``proc.run``."""

    def tool(argv: list[str], *, stdout_path: Any = None, **_kw: Any) -> Any:
        res = proc.run([str(a) for a in argv], check=False, stdout_path=stdout_path, cwd=workdir)
        return subprocess.CompletedProcess(res.argv, res.returncode, res.stdout, res.stderr)

    return tool


def make_ctx(
    img: Path,
    run_dir: Path,
    module: str,
    *,
    options: dict[str, Any] | None = None,
    shared: dict[str, Any] | None = None,
    volumes: tuple[Volume, ...] | None = None,
) -> tuple[ModuleContext, list[dict[str, Any]]]:
    """A ModuleContext whose ``emit`` checks each row against schema.json and keeps it."""
    rows: list[dict[str, Any]] = []
    workdir = run_dir / "modules" / module
    workdir.mkdir(parents=True, exist_ok=True)

    def emit(row: dict[str, Any]) -> None:
        full = findings.normalise_row(row)
        full.update(run_id=RUN_ID, evidence_id="EX-1", evidence_sha256=EVIDENCE_SHA)
        errors = findings.validate_row(full, part=True)
        assert not errors, (errors, row)
        rows.append(full)

    vols = volumes or (Volume(0, 0, img.stat().st_size, "ntfs"),)
    ctx = ModuleContext(
        run_id=RUN_ID,
        module=module,
        target=Target(path=img, kind="image", evidence_id="EX-1", volumes=vols),
        run_dir=run_dir,
        workdir=workdir,
        options=options or {"preset": "standard"},
        emit=emit,
        tool=tool_runner(workdir),
        log=lambda *_a, **_k: None,
        tool_version=lambda name: f"{name} test",
        shared=shared if shared is not None else {},
    )
    return ctx, rows


def stub_tool(folder: Path, name: str, body: str) -> Path:
    """Write an executable stub (a stand-in for a tool not installed here) into ``folder``."""
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / name
    path.write_text("#!/usr/bin/env python3\n" + body)
    path.chmod(0o755)
    return path


@pytest.fixture(scope="module")
def built(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, dict[str, Any]]:
    why = ntfs_tools_ok()
    if why:
        pytest.skip(why)
    img = tmp_path_factory.mktemp("ntfs") / "fixture.img"
    return img, build_ntfs_image(img)


def test_fixture_holds_ground_truth(built: tuple[Path, dict[str, Any]]) -> None:
    img, truth = built
    out = subprocess.run(["fls", "-r", "-p", str(img)], capture_output=True, text=True, check=True)
    listing = out.stdout
    for path in truth["live"]:
        assert f"\t{path.lstrip('/')}\n" in listing
    for path in truth["deleted"]:
        line = next(ln for ln in listing.splitlines() if ln.endswith("\t" + path.lstrip("/")))
        assert "*" in line.split("\t")[0], line
    assert "$Recycle.Bin/S-1-5-21-111-222-333-1001/$IZZ99YY.txt" in listing
    assert "keep.txt:extra" in listing
