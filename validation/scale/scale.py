#!/usr/bin/env python3
"""Scale test (task 4G.15): a big NTFS image, run time and peak memory per module, baseline.

Host side or CI, needs root. Standard library only.

    scale.py generate --out big.img --files 300000
    scale.py run --image big.img --out OUT [--preset standard] [--baseline baseline.json]
                 [--update-baseline] [--key NAME]
    scale.py compare --result OUT/result.json [--baseline baseline.json] [--key NAME]

``generate`` writes the image through ``ntfs-3g`` (generated bytes only) and a manifest
``<image>.json``; the file count is a parameter. ``run`` attaches the image read-only, runs
``forensic-analyze`` on it, samples the resident memory of the whole process tree (the wizard,
the sandbox and every tool) from ``/proc`` while it runs, and takes the peak of any single
process from ``getrusage(RUSAGE_CHILDREN)`` (that one can miss tools reaped inside the
sandbox's own process namespace, so both are kept and both are compared). Each sample is
given to the module that was running at that moment (``run.json`` start times and
durations). The result goes to ``OUT/result.json`` and is compared with the stored
baseline for the same key (``<preset>-<files>``): a run more than the tolerance slower, or
using more memory, fails.

Exit status: 0 within tolerance (or no baseline for this key yet), 1 regression or failure,
2 usage error, 77 a prerequisite is missing.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import resource
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
BASELINE = HERE / "baseline.json"
SCHEMA = 1
GENERATOR = "validation/scale/scale.py 1"
DEFAULT_TOL = {"time": 0.5, "memory": 0.3, "slack_s": 5.0, "slack_kib": 131072}
PAGE_KIB = os.sysconf("SC_PAGE_SIZE") // 1024


class ScaleError(RuntimeError):
    """The scale test could not run."""


# -- generate ----------------------------------------------------------------------------------


def file_plan(index: int) -> tuple[str, int]:
    """Extension and size of file ``index``: mostly small binary files, some larger ones."""
    ext = ".txt" if index % 100 == 7 else ".bin"
    size = 4096 + (index % 4) * 1024 if index % 20 == 3 else (index * 37) % 600
    return ext, size


def generate(
    out: Path, files: int, *, per_dir: int = 1000, deleted_every: int = 25
) -> dict[str, Any]:
    if files < 1 or per_dir < 1:
        raise ScaleError("--files and --per-dir must be positive")
    size_mib = max(64, (files * 2 * 1024 + files // 20 * 8192) // (1024 * 1024) + 64)
    out.unlink(missing_ok=True)
    with open(out, "wb") as fh:
        fh.truncate(size_mib * 1024 * 1024)
    _run(["mkfs.ntfs", "-Q", "-F", "-L", "AIRLOCKSCALE", str(out)])
    mnt = Path(tempfile.mkdtemp(prefix="airlock-scale."))
    t0 = time.monotonic()
    deleted = 0
    try:
        _run(["ntfs-3g", str(out), str(mnt)])
        try:
            for i in range(files):
                folder = mnt / f"d{i // per_dir:05d}"
                if i % per_dir == 0:
                    folder.mkdir()
                ext, size = file_plan(i)
                (folder / f"f{i:07d}{ext}").write_bytes(
                    (i.to_bytes(4, "little") * (size // 4 + 1))[:size]
                )
            for i in range(0, files, deleted_every):
                ext, _ = file_plan(i)
                (mnt / f"d{i // per_dir:05d}" / f"f{i:07d}{ext}").unlink()
                deleted += 1
            os.sync()
        finally:
            subprocess.run(["umount", str(mnt)], check=False, capture_output=True)
    finally:
        mnt.rmdir()
    manifest = {
        "schema": SCHEMA,
        "generator": GENERATOR,
        "image": out.name,
        "files": files,
        "deleted": deleted,
        "directories": (files + per_dir - 1) // per_dir,
        "size_mib": size_mib,
        "generate_s": round(time.monotonic() - t0, 1),
    }
    Path(f"{out}.json").write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n")
    return manifest


def _run(argv: list[str]) -> str:
    res = subprocess.run(argv, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        raise ScaleError(f"{argv[0]} failed (exit {res.returncode}): {res.stderr.strip()[-300:]}")
    return res.stdout


# -- memory sampling ---------------------------------------------------------------------------


def _ppid_map() -> dict[int, list[int]]:
    children: dict[int, list[int]] = {}
    for entry in os.listdir("/proc"):
        if not entry.isdigit():
            continue
        try:
            with open(f"/proc/{entry}/stat", encoding="ascii", errors="replace") as fh:
                stat = fh.read()
        except OSError:
            continue
        # The command name may hold spaces and brackets: fields resume after the last ')'.
        fields = stat.rsplit(")", 1)[-1].split()
        if len(fields) > 1:
            children.setdefault(int(fields[1]), []).append(int(entry))
    return children


def tree_rss_kib(root: int) -> int:
    """Summed resident memory of ``root`` and all its descendants, in KiB."""
    children = _ppid_map()
    total, todo, seen = 0, [root], set()
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        try:
            with open(f"/proc/{pid}/statm", encoding="ascii") as fh:
                total += int(fh.read().split()[1]) * PAGE_KIB
        except (OSError, IndexError, ValueError):
            pass
        todo.extend(children.get(pid, []))
    return total


def _epoch(text: str) -> float:
    return dt.datetime.fromisoformat(text.replace("Z", "+00:00")).timestamp()


def attribute(
    samples: list[tuple[float, int]], modules: list[dict[str, Any]]
) -> dict[str, dict[str, Any]]:
    """Per-module duration and the peak tree RSS sampled while that module ran."""
    out: dict[str, dict[str, Any]] = {}
    for m in modules:
        rec: dict[str, Any] = {
            "status": m.get("status"),
            "duration_s": m.get("duration_s"),
            "peak_tree_rss_kib": None,
        }
        if m.get("started_utc") and m.get("duration_s") is not None:
            start = _epoch(m["started_utc"])
            end = start + float(m["duration_s"])
            inside = [rss for t, rss in samples if start <= t <= end]
            if inside:
                rec["peak_tree_rss_kib"] = max(inside)
        out[str(m["name"])] = rec
    return out


# -- compare -----------------------------------------------------------------------------------


def load_baseline(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {"schema": SCHEMA, "tolerance": dict(DEFAULT_TOL), "baselines": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def _over(value: Any, base: Any, rel: float, slack: float) -> bool:
    if value is None or base is None:
        return False
    return float(value) > float(base) * (1 + rel) + slack


def compare(
    result: dict[str, Any], base: dict[str, Any] | None, tol: dict[str, float]
) -> list[str]:
    """Regression lines (empty = within tolerance)."""
    if not base:
        return []
    t, m = tol.get("time", DEFAULT_TOL["time"]), tol.get("memory", DEFAULT_TOL["memory"])
    ss, sk = (
        tol.get("slack_s", DEFAULT_TOL["slack_s"]),
        tol.get("slack_kib", DEFAULT_TOL["slack_kib"]),
    )
    out = []
    if _over(result.get("total_s"), base.get("total_s"), t, ss):
        out.append(f"total run time {result['total_s']} s, baseline {base['total_s']} s")
    for key, what in (("peak_tree_rss_kib", "process tree"), ("peak_rss_kib", "single process")):
        if _over(result.get(key), base.get(key), m, sk):
            out.append(f"peak memory ({what}) {result[key]} KiB, baseline {base[key]} KiB")
    for name, b in sorted((base.get("modules") or {}).items()):
        r = (result.get("modules") or {}).get(name)
        if r is None:
            continue
        if b.get("status") == "ok" and r.get("status") != "ok":
            out.append(f"module {name}: status {r.get('status')}, baseline ok")
        if _over(r.get("duration_s"), b.get("duration_s"), t, ss):
            out.append(f"module {name}: {r['duration_s']} s, baseline {b['duration_s']} s")
        if _over(r.get("peak_tree_rss_kib"), b.get("peak_tree_rss_kib"), m, sk):
            out.append(
                f"module {name}: peak memory {r['peak_tree_rss_kib']} KiB, "
                f"baseline {b['peak_tree_rss_kib']} KiB"
            )
    return out


def host_info() -> dict[str, Any]:
    mem = 0
    try:
        for line in Path("/proc/meminfo").read_text().splitlines():
            if line.startswith("MemTotal:"):
                mem = int(line.split()[1])
    except OSError:
        pass
    return {
        "cpus": os.cpu_count(),
        "mem_total_kib": mem,
        "kernel": platform.release(),
        "python": platform.python_version(),
    }


# -- run ---------------------------------------------------------------------------------------


def analyze_cmd(given: str | None) -> list[str]:
    if given:
        return [given]
    repo_bin = REPO / "ansible" / "roles" / "session_tools" / "files" / "bin" / "forensic-analyze"
    if repo_bin.is_file():
        os.environ.setdefault(
            "AIRLOCK_PYLIB", str(REPO / "ansible" / "roles" / "session_tools" / "files" / "pylib")
        )
        return [str(repo_bin)]
    found = shutil.which("forensic-analyze")
    if not found:
        raise ScaleError("forensic-analyze not found; pass --analyze")
    return [found]


def run_scale(args: argparse.Namespace) -> dict[str, Any]:
    if os.geteuid() != 0:
        raise ScaleError("needs root (read-only loop device)")
    manifest_path = Path(f"{args.image}.json")
    manifest = json.loads(manifest_path.read_text()) if manifest_path.is_file() else {}
    out: Path = args.out
    if out.exists():
        shutil.rmtree(out)
    env_root = out / "env"
    for name, sub in (
        ("AIRLOCK_OPT_DIR", "opt"),
        ("AIRLOCK_ETC_DIR", "etc"),
        ("AIRLOCK_STATE_DIR", "state"),
        ("AIRLOCK_SESSION_DIR", "session"),
        ("AIRLOCK_ASSETS_DIR", "assets"),
    ):
        (env_root / sub).mkdir(parents=True, exist_ok=True)
        os.environ[name] = str(env_root / sub)
    runs = out / "runs"
    runs.mkdir(parents=True)
    os.environ["AIRLOCK_OUTPUT_DIR"] = str(runs)
    cmd = analyze_cmd(args.analyze)
    loop = _run(["losetup", "-r", "-f", "--show", str(args.image)]).strip()
    samples: list[tuple[float, int]] = []
    try:
        argv = [
            *cmd,
            "--authority-ack",
            "--yes",
            "--examiner",
            "AIRLOCK scale test",
            "--case-id",
            "SCALE",
            "--target",
            loop,
            "--preset",
            args.preset,
            "--output",
            str(runs),
            "--write-blocker",
            "no",
            "--reference-time",
            dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "--reference-source",
            "scale test host clock (not a trusted reference)",
        ]
        t0 = time.monotonic()
        with open(out / "analyze.log", "wb") as log:
            proc = subprocess.Popen(argv, stdout=log, stderr=subprocess.STDOUT)
            while proc.poll() is None:
                samples.append((time.time(), tree_rss_kib(proc.pid)))
                time.sleep(args.interval)
            rc = proc.wait()
        total = time.monotonic() - t0
    finally:
        subprocess.run(["losetup", "-d", loop], check=False, capture_output=True)
    ru_max = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
    run_dirs = sorted((runs / "cases" / "SCALE").glob("R-*"))
    if not run_dirs or not (run_dirs[-1] / "run.json").is_file():
        raise ScaleError(f"forensic-analyze exited {rc} without a run; see {out / 'analyze.log'}")
    run_doc = json.loads((run_dirs[-1] / "run.json").read_text(encoding="utf-8"))
    modules = [m for m in run_doc.get("modules", []) if m.get("status") != "not_available"]
    return {
        "schema": SCHEMA,
        "generator": GENERATOR,
        "files": manifest.get("files"),
        "deleted": manifest.get("deleted"),
        "preset": args.preset,
        "exit_code": rc,
        "run_id": run_doc.get("run_id"),
        "run_status": run_doc.get("status"),
        "findings_rows": (run_doc.get("findings") or {}).get("rows"),
        "total_s": round(total, 2),
        "peak_rss_kib": ru_max,
        "peak_tree_rss_kib": max((s for _, s in samples), default=None),
        "sample_interval_s": args.interval,
        "samples": len(samples),
        "modules": attribute(samples, modules),
        "host": host_info(),
        "measured_utc": dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }


def finish(result: dict[str, Any], baseline_path: Path, key: str, update: bool) -> int:
    doc = load_baseline(baseline_path)
    tol = {**DEFAULT_TOL, **(doc.get("tolerance") or {})}
    base = (doc.get("baselines") or {}).get(key)
    result["baseline_key"] = key
    result["tolerance"] = tol
    if result.get("exit_code") not in (0, None) or result.get("run_status") not in (
        "complete",
        None,
    ):
        result["regressions"] = [f"the run did not complete (exit {result.get('exit_code')})"]
    else:
        result["regressions"] = compare(result, base, tol)
    if update:
        keep = {k: v for k, v in result.items() if k not in {"regressions", "verdict", "tolerance"}}
        doc.setdefault("baselines", {})[key] = keep
        doc.setdefault("tolerance", tol)
        baseline_path.write_text(json.dumps(doc, sort_keys=True, indent=2) + "\n", encoding="utf-8")
        result["verdict"] = "baseline recorded"
        return 0
    if result["regressions"]:
        result["verdict"] = "fail"
        return 1
    result["verdict"] = "pass" if base else "no baseline"
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Scale test for forensic-analyze (task 4G.15).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate", help="build an NTFS image with many files")
    g.add_argument("--out", type=Path, required=True)
    g.add_argument("--files", type=int, required=True, help="number of files, e.g. 300000")
    g.add_argument("--per-dir", type=int, default=1000)
    g.add_argument("--deleted-every", type=int, default=25, help="delete every Nth file")
    r = sub.add_parser("run", help="analyse the image and compare with the baseline")
    r.add_argument("--image", type=Path, required=True)
    r.add_argument("--out", type=Path, required=True)
    r.add_argument("--preset", default="standard", choices=("quick", "standard", "full"))
    r.add_argument("--baseline", type=Path, default=BASELINE)
    r.add_argument("--key", help="baseline key (default: <preset>-<files>)")
    r.add_argument("--update-baseline", action="store_true")
    r.add_argument("--analyze", help="forensic-analyze command")
    r.add_argument("--interval", type=float, default=0.2, help="memory sample interval (s)")
    c = sub.add_parser("compare", help="compare a stored result with the baseline")
    c.add_argument("--result", type=Path, required=True)
    c.add_argument("--baseline", type=Path, default=BASELINE)
    c.add_argument("--key")
    args = ap.parse_args(argv)
    try:
        if args.cmd == "generate":
            if os.geteuid() != 0:
                raise ScaleError("needs root (ntfs-3g mount)")
            m = generate(
                args.out, args.files, per_dir=args.per_dir, deleted_every=args.deleted_every
            )
            print(f"scale: {args.out}: {m['files']} files, {m['deleted']} deleted, ", end="")
            print(f"{m['generate_s']} s")
            return 0
        if args.cmd == "run":
            result = run_scale(args)
            key = args.key or f"{args.preset}-{result['files']}"
            rc = finish(result, args.baseline, key, args.update_baseline)
            (args.out / "result.json").write_text(
                json.dumps(result, sort_keys=True, indent=2) + "\n"
            )
        else:
            result = json.loads(args.result.read_text(encoding="utf-8"))
            key = args.key or result.get("baseline_key") or f"{result['preset']}-{result['files']}"
            rc = finish(result, args.baseline, key, False)
        peak = result.get("peak_tree_rss_kib")
        print(
            f"scale: {result.get('files')} files, {result['total_s']} s, "
            f"peak {peak} KiB (process tree): {result['verdict']}"
        )
        for line in result.get("regressions", []):
            print(f"scale: regression: {line}")
        return rc
    except (ScaleError, OSError, ValueError, KeyError) as exc:
        print(f"scale: {exc}. Fix that and run again.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
